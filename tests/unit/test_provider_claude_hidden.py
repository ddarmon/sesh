"""Claude hidden-record classification, slash commands, and empty sessions."""

from __future__ import annotations

from pathlib import Path

from sesh.models import Provider, filter_messages
from sesh.providers import claude
from tests.helpers import make_session, write_jsonl

SID = "session"


def _user(uuid: str, parent: str | None, content, second: int, **extra) -> dict:
    return {"type": "user", "uuid": uuid, "parentUuid": parent, "sessionId": SID,
            "timestamp": f"2026-01-01T00:00:{second:02d}Z",
            "message": {"role": "user", "content": content}, **extra}


def _assistant(uuid: str, parent: str, text: str, second: int, model="claude-opus") -> dict:
    return {"type": "assistant", "uuid": uuid, "parentUuid": parent, "sessionId": SID,
            "timestamp": f"2026-01-01T00:00:{second:02d}Z",
            "message": {"role": "assistant", "model": model,
                        "content": [{"type": "text", "text": text}]}}


CAVEAT = "<local-command-caveat>Caveat: The messages below were generated by the user.</local-command-caveat>"
MODEL_CMD = (
    "<command-name>/model</command-name>\n"
    "            <command-message>model</command-message>\n"
    "            <command-args></command-args>"
)
MODEL_OUT = "<local-command-stdout>Set model to Sonnet</local-command-stdout>"


def _model_only_records() -> list[dict]:
    """A session where the user only ran ``/model`` (Claude Code 2.1.301 shape)."""
    return [
        {"type": "mode", "mode": "normal", "sessionId": SID},
        _user("u1", None, CAVEAT, 1, isMeta=True),
        _user("u2", "u1", MODEL_CMD, 2),
        _user("u3", "u2", MODEL_OUT, 3),
        {"type": "last-prompt", "leafUuid": "u3", "sessionId": SID},
    ]


def _load(path: Path):
    session = make_session(id=SID, provider=Provider.CLAUDE, source_path=str(path))
    return claude.ClaudeProvider().get_messages(session)


def test_local_command_session_is_hidden_and_empty(tmp_path: Path) -> None:
    """``/model`` alone: every record hidden, session empty and titled by command."""
    path = tmp_path / "s.jsonl"
    write_jsonl(path, _model_only_records())

    messages = _load(path)
    assert [m.content for m in messages] == [CAVEAT, "/model", MODEL_OUT]
    assert all(m.is_system for m in messages)
    assert filter_messages(messages) == []
    assert [m.content for m in filter_messages(messages, include_system=True)] == [
        CAVEAT, "/model", MODEL_OUT
    ]

    meta = claude.ClaudeProvider()._parse_sessions(tmp_path, "/repo")[0]
    assert meta.is_empty is True
    assert meta.summary == "/model · no conversation"

    loose_meta, _ = claude.load_loose_session(path)
    assert loose_meta.is_empty is True
    assert loose_meta.summary == "/model · no conversation"


def test_prompt_command_shows_as_typed_and_hides_expansion(tmp_path: Path) -> None:
    """A command that drives a turn stays visible as ``/name args``."""
    path = tmp_path / "s.jsonl"
    write_jsonl(path, [
        _user("u1", None,
              "<command-message>tutor-start</command-message>\n"
              "<command-name>/tutor-start</command-name>\n"
              "<command-args>linear algebra</command-args>", 1),
        _user("u2", "u1", [{"type": "text", "text": "Load the `pi-tutor` skill and start."}],
              2, isMeta=True),
        _assistant("a1", "u2", "Starting the session.", 3),
    ])

    visible = filter_messages(_load(path))
    assert [(m.role, m.content) for m in visible] == [
        ("user", "/tutor-start linear algebra"),
        ("assistant", "Starting the session."),
    ]

    meta = claude.ClaudeProvider()._parse_sessions(tmp_path, "/repo")[0]
    assert meta.is_empty is False
    # No hand-written prompt: the typed command titles the session.
    assert meta.summary == "/tutor-start linear algebra"


def test_injected_text_is_hidden_but_interrupts_stay_visible(tmp_path: Path) -> None:
    """isMeta skill bodies and task notifications hide; interrupts show but never title."""
    path = tmp_path / "s.jsonl"
    write_jsonl(path, [
        _user("u1", None, "Please review the branch", 1),
        _user("u2", "u1", [{"type": "text", "text": "Base directory for this skill: /x\n\n# Skill"}],
              2, isMeta=True),
        _assistant("a1", "u2", "Reviewing.", 3),
        _user("u3", "a1", "<task-notification>\n<status>completed</status>", 4),
        _user("u4", "u3", [{"type": "text", "text": "[Request interrupted by user]"}], 5),
    ])

    visible = filter_messages(_load(path))
    assert [m.content for m in visible] == [
        "Please review the branch", "Reviewing.", "[Request interrupted by user]"
    ]
    meta = claude.ClaudeProvider()._parse_sessions(tmp_path, "/repo")[0]
    assert meta.summary == "Please review the branch"
    assert meta.is_empty is False


def test_synthetic_reply_alone_is_not_dialogue(tmp_path: Path) -> None:
    """Claude's own ``<synthetic>`` replies don't make a session non-empty."""
    path = tmp_path / "s.jsonl"
    write_jsonl(path, [
        *_model_only_records()[:4],
        _assistant("a1", "u3", "No response requested.", 4, model="<synthetic>"),
    ])
    assert claude.ClaudeProvider()._parse_sessions(tmp_path, "/repo")[0].is_empty is True

    # ...but a real prompt answered only by a synthetic error is a conversation.
    write_jsonl(path, [
        _user("u1", None, "Explain this", 1),
        _assistant("a1", "u1", "You've hit your session limit", 2, model="<synthetic>"),
    ])
    meta = claude.ClaudeProvider()._parse_sessions(tmp_path, "/repo")[0]
    assert meta.is_empty is False
    assert meta.summary == "Explain this"


def test_command_display_parses_both_tag_orders() -> None:
    assert claude._command_display(MODEL_CMD) == "/model"
    assert claude._command_display(
        "<command-message>release</command-message>\n<command-name>/release</command-name>"
    ) == "/release"
    assert claude._command_display("plain prompt") is None
